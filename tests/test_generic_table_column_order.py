"""
test_generic_table_column_order.py
----------------------------------
Test suite validating the mandatory generic table column order envelope
for every table generated by the DDL/schema generation process.

MANDATORY ENVELOPE REQUIREMENTS:
FIRST:
  1. ctrl_id int4 NULL
  2. exec_seq int4 NULL
  3. execution_date date NULL
  4. execution_schedule varchar(100) NULL

THEN:
  5+. All remaining columns from the source/business mapping.

LAST:
  - create_dtm timestamp DEFAULT now() NULL
  - update_dtm timestamp DEFAULT now() NULL
  - updated_by varchar(50) NULL
  - processing_date date NULL

CRITICAL CONSTRAINTS:
- ctrl_id MUST be the first column.
- exec_seq MUST be the second column.
- execution_date MUST be the third column.
- execution_schedule MUST be the fourth column.
- "id" is NOT a generic required column and must NOT be added automatically.
- Source/business columns must remain in the middle.
- The 4 audit/processing columns must always be the final 4 columns in exactly this order.
- No duplication if envelope columns already exist in source mapping.
- Source columns must not be dropped.
- Source columns must not be invented.
- Generic across all tables and controls.
"""

import os
