def test_replicated_source_tables_ddl():
    """Test generate_source_tables_ddl outputs standard envelope."""
    sources = [{"source_table": "raw_orders", "source_system": "sys_oms"}]
    introspect = {
        "raw_orders": {
            "table_found": True,
            "found_in_db": "PostgreSQL",
            "columns": [
                {"column_name": "order_id", "data_type": "VARCHAR(50)"},
                {"column_name": "order_amount", "data_type": "NUMERIC(12,2)"},
                {"column_name": "order_date", "data_type": "DATE"},
            ],
        }
    }
    analysis = {
        "rules": {
            "filter_rules": [
                {"data_stream": "raw_orders", "rule_statement": "Filter (order_id, order_amount, order_date)"}
            ]
        }
    }
    ddl = generate_source_tables_ddl("ra_ctrl.ctrl_01", "postgresql", sources, introspect, analysis)
    parsed = _parse_required_objects_from_ddl(ddl)
    assert len(parsed) == 1
    _assert_standard_envelope("raw_orders", parsed[0]["columns"], ["order_id", "order_amount", "order_date"])
    print("TEST 3 PASS - Replicated source table DDL conforms to generic column envelope")


