def test_cross_control_generality():
    """Verify that multiple distinct controls (CTRL-05, CTRL-23, CTRL-99) all enforce generic envelope."""
    controls = ["CTRL-05", "CTRL-23", "CTRL-99", "CTRL-CUSTOM"]
    for c_num in controls:
        mock_analysis = {
            "control_overview": {"identification": {"control_number": c_num}},
            "config_tables": [{"config_table_name": "cfg_control_params", "target_column": "param_val"}],
        }
        mock_sources = [{"source_table": "src_events", "source_system": "sys_ev"}]
        mock_introspect = {
            "src_events": {
                "table_found": True,
                "found_in_db": "PostgreSQL",
                "columns": [{"column_name": "event_code", "data_type": "VARCHAR(30)"}],
            }
        }
        mock_rules = {
            "filter_rules": [{"data_stream": "src_events", "rule_statement": "Filter (event_code)"}]
        }
        ddl = generate_target_ddl(
            f"ra_ctrl.{c_num.lower()}",
            "postgresql",
            mock_sources,
            mock_rules,
            [],
            mock_introspect,
            mock_analysis,
        )
        parsed = _parse_required_objects_from_ddl(ddl)
        for t in parsed:
            _assert_standard_envelope(f"{c_num}:{t['bare_name']}", t["columns"])

    print("TEST 5 PASS - Generality verified across multiple controls without hardcoded assumptions")


def test_exact_sql_snippet_structure():
    """Verify the exact SQL string for the 4 initial columns and 4 final columns."""
    res = build_table_columns_with_standard_envelope(["    my_col VARCHAR(50)"], target_dialect="postgresql")
    ddl_block = ",\n".join(res)

    # Check exact keywords from user specification:
    assert "ctrl_id int4 NULL" in ddl_block
    assert "exec_seq int4 NULL" in ddl_block
    assert "execution_date date NULL" in ddl_block
    assert "execution_schedule varchar(100) NULL" in ddl_block
    assert "create_dtm timestamp DEFAULT now() NULL" in ddl_block
    assert "update_dtm timestamp DEFAULT now() NULL" in ddl_block
    assert "updated_by varchar(50) NULL" in ddl_block
    assert "processing_date date NULL" in ddl_block

    # Assert no automatic id column
    assert "\n    id " not in ddl_block
    assert "\n    id int4" not in ddl_block
    assert "GENERATED BY DEFAULT AS IDENTITY" not in ddl_block

    print("TEST 6 PASS - Exact SQL structure matches user specification (4-prefix and 4-suffix without id)")


