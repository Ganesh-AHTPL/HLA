# TEST 7 — Existing table missing a normal column ? valid ALTER generated
# ------------------------------------------------------------------------------
def test_7_alter_for_missing_column():
    ddl = """
    CREATE TABLE schema1.partial (
        id     BIGINT,
        name   TEXT,
        status VARCHAR(16)
    );
    """
    req = _parse_required_objects_from_ddl(ddl)
    # Simulate: id and name exist, status is missing
    existing_cols = [
        {"name": "id",   "data_type": "bigint",  "is_nullable": True},
        {"name": "name", "data_type": "text",    "is_nullable": True},
    ]
    tables = {"partial": _existing(existing_cols)}
    report = reconcile_objects(_meta(True, tables), req)
    assert report["counts"]["different"] == 1
    diff_obj = next(v for v in report["objects"].values() if v["status"] == "DIFFERENT")
    missing = diff_obj["missing_columns"]
    assert len(missing) == 1 and missing[0]["name"] == "status"
    results = _build_alter_statements("schema1", "partial", missing, "postgresql")
    assert len(results) == 1
    stmt, is_safe, reason = results[0]
    assert is_safe, f"Normal column ALTER should be safe: {reason}"
    assert "status" in stmt.lower()
    assert "varchar" in stmt.lower() or "character varying" in stmt.lower()
    # Must not contain incomplete fragment
    assert not re.search(r'\bVARCHAR\s*;', stmt, re.IGNORECASE), f"Incomplete ALTER: {stmt}"
    print("TEST 7 PASS — valid ALTER generated for missing normal column")

