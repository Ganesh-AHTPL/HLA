# TEST 1 — Simple columns: BIGINT, VARCHAR(100)
# ------------------------------------------------------------------------------
def test_1_simple_columns():
    ddl = """
    CREATE TABLE schema1.simple (
        id   BIGINT,
        name VARCHAR(100)
    );
    """
    req = _parse_required_objects_from_ddl(ddl)
    assert len(req) == 1, f"Expected 1 table, got {len(req)}"
    cols = req[0]["columns"]
    names = {c["name"] for c in cols}
    assert "id" in names and "name" in names, f"Missing cols: {names}"
    id_col = _find_col(cols, "id")
    assert "bigint" in id_col["data_type"].lower(), f"id type: {id_col['data_type']}"
    name_col = _find_col(cols, "name")
    assert "varchar" in name_col["data_type"].lower() or "character" in name_col["data_type"].lower(), \
        f"name type: {name_col['data_type']}"
    print("TEST 1 PASS — simple columns")

