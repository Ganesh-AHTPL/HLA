# TEST 12 — SQL Parser test cases (Cases 1-5 + Master Comments)
# ------------------------------------------------------------------------------
def test_12_sql_parser_cases():
    # CASE 1: -- comment only -> SKIP
    case1 = "-- comment only"
    assert not _has_executable_sql(case1), "Case 1 failed: comment only should not be executable"
    stmts1 = _split_sql_statements(case1)
    assert len(stmts1) == 0, f"Case 1 failed: expected 0 statements, got {len(stmts1)}"

    # CASE 2: -- comment \n CREATE TABLE test_table (id BIGINT); -> CREATE statement only
    case2 = """-- comment
    CREATE TABLE test_table (id BIGINT);"""
    assert _has_executable_sql(case2), "Case 2 failed: should have executable SQL"
    stmts2 = _split_sql_statements(case2)
    assert len(stmts2) == 1, f"Case 2 failed: expected 1 statement, got {len(stmts2)}"
    assert "CREATE TABLE test_table" in stmts2[0], f"Case 2 statement content mismatch: {stmts2[0]}"

    # CASE 3: DO $$ BEGIN PERFORM 1; END $$; -> ONE statement
    case3 = """DO $$
    BEGIN
        PERFORM 1;
    END $$;"""
    assert _has_executable_sql(case3), "Case 3 failed: DO block should be executable"
    stmts3 = _split_sql_statements(case3)
    assert len(stmts3) == 1, f"Case 3 failed: expected 1 statement, got {len(stmts3)}"
    assert "PERFORM 1" in stmts3[0], f"Case 3 content mismatch: {stmts3[0]}"

    # CASE 4: CREATE TABLE test (name VARCHAR(100), description TEXT DEFAULT 'abc;def'); -> ONE statement
    case4 = """CREATE TABLE test (
        name VARCHAR(100),
        description TEXT DEFAULT 'abc;def'
    );"""
    assert _has_executable_sql(case4), "Case 4 failed: CREATE table with semicolon in string"
    stmts4 = _split_sql_statements(case4)
    assert len(stmts4) == 1, f"Case 4 failed: expected 1 statement, got {len(stmts4)}"
    assert "'abc;def'" in stmts4[0], f"Case 4 content mismatch: {stmts4[0]}"

    # CASE 5: ALTER TABLE "ra_ctrl.ctrl_23".ctrl_config ADD COLUMN IF NOT EXISTS test_column TEXT;
    case5 = """ALTER TABLE "ra_ctrl.ctrl_23".ctrl_config
    ADD COLUMN IF NOT EXISTS test_column TEXT;"""
    assert _has_executable_sql(case5), "Case 5 failed: ALTER TABLE with quoted dot identifier"
    stmts5 = _split_sql_statements(case5)
    assert len(stmts5) == 1, f"Case 5 failed: expected 1 statement, got {len(stmts5)}"
    assert '"ra_ctrl.ctrl_23".ctrl_config' in stmts5[0]

    # CASE 6: DDL with master table comments (the exact trigger for psycopg2 empty query error)
    case6 = """-- ============================================================================
-- MASTER / REFERENCE TABLES (PRE-EXISTING IN TARGET SCHEMA — NOT CREATED)
-- Naming convention: ra_ctrl.ctrl_23.ctrl_23_<table_name>
-- e.g. "ra_ctrl.ctrl_23".ctrl_23_bucket_config
-- These tables exist in the target schema
"""
    assert not _has_executable_sql(case6), "Case 6 failed: master comments block must be non-executable"
    stmts6 = _split_sql_statements(case6)
    assert len(stmts6) == 0, f"Case 6 failed: expected 0 statements from master comments, got {len(stmts6)}"
    print("TEST 12 PASS — all SQL parser test cases verified (Cases 1-5 + Master Comments)")

