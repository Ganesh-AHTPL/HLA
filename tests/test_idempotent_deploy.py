# TEST 9 — _is_alter_safe rejects incomplete fragments
# ------------------------------------------------------------------------------
def test_9_alter_safety_validator():
    # These must be REJECTED
    bad = [
        "ALTER TABLE s.t ADD COLUMN IF NOT EXISTS id BIGINT GENERATED BY;",
        "ALTER TABLE s.t ADD COLUMN IF NOT EXISTS id BIGINT GENERATED ALWAYS;",
        "ALTER TABLE s.t ADD COLUMN IF NOT EXISTS created_at DEFAULT;",
        "ALTER TABLE s.t ADD COLUMN IF NOT EXISTS name VARCHAR;",
        "ALTER TABLE s.t ADD COLUMN IF NOT EXISTS val NUMERIC;",
        "ALTER TABLE s.t ADD COLUMN IF NOT EXISTS val BIGINT",   # no semicolon
    ]
    for stmt in bad:
        safe, reason = _is_alter_safe(stmt)
        assert not safe, f"Should be UNSAFE: {stmt!r}"

    # These must be ACCEPTED
    good = [
        "ALTER TABLE s.t ADD COLUMN IF NOT EXISTS id BIGINT GENERATED BY DEFAULT AS IDENTITY;",
        "ALTER TABLE s.t ADD COLUMN IF NOT EXISTS created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP;",
        "ALTER TABLE s.t ADD COLUMN IF NOT EXISTS name VARCHAR(64);",
        "ALTER TABLE s.t ADD COLUMN IF NOT EXISTS amount NUMERIC(18,2);",
    ]
    for stmt in good:
        safe, reason = _is_alter_safe(stmt)
        assert safe, f"Should be SAFE: {stmt!r} — reason: {reason}"

    print("TEST 9 PASS — _is_alter_safe correctly validates/rejects ALTER statements")

