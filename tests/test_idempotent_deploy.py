# TEST 11 — Generic: works for any control ID (CTRL-N)
# ------------------------------------------------------------------------------
def test_11_cross_control_generic():
    for ctrl_n in [6, 23, 99, 112]:
        schema = f"ra_ctrl_{ctrl_n}"
        ddl = f"""
        CREATE TABLE IF NOT EXISTS {schema}.ctrl_stg_{ctrl_n} (
            run_id   INTEGER NOT NULL,
            val      NUMERIC(18,4),
            calc_ts  TIMESTAMP DEFAULT NOW()
        );
        """
        req = _parse_required_objects_from_ddl(ddl)
        assert len(req) == 1, f"ctrl_{ctrl_n}: expected 1 table"
        cols = req[0]["columns"]
        assert len(cols) == 3, f"ctrl_{ctrl_n}: expected 3 cols, got {len(cols)}: {[c['name'] for c in cols]}"
        # Sandbox deploy must succeed and mention the schema in stages
        cfg = {"db_type": "sandbox", "schema_name": schema}
        success, msg, recon, stages = idempotent_deploy(cfg, ddl, analysis_data={"ctrl_id_info": {"control_id": str(ctrl_n)}})
        assert success, f"ctrl_{ctrl_n}: deploy failed: {msg}"
        stage_text = " ".join(s["label"] for s in stages).lower()
        assert schema in stage_text, f"ctrl_{ctrl_n}: schema not in stages: {stage_text}"
        # No hardcoded control numbers from other controls (e.g. ctrl_23 hardcoded during ctrl_6 test)
        for s in stages:
            for other_n in [x for x in [6, 23, 99, 112] if x != ctrl_n]:
                assert not re.search(rf"ctrl[-_ ]{other_n}\b", s.get("label", "").lower()), \
                    f"hardcoded foreign control number {other_n} in stages for ctrl_{ctrl_n}: {s['label']}"
    print("TEST 11 PASS — generic across multiple control identifiers")

