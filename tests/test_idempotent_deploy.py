    stmt, is_safe, reason = results[0]
    assert not is_safe, f"Generated-stored ALTER should be unsafe: {stmt}"
    assert "UNSAFE" in stmt.upper() or "cannot" in reason.lower()
    print("TEST 3 PASS — generated stored column: unsafe ALTER flagged")

