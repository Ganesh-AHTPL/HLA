# -- helpers --------------------------------------------------------------------
def _existing(cols):
    return {"exists": True, "columns": cols, "column_names": {c["name"] for c in cols}}

def _meta(schema_exists, tables):
    return {"schema_exists": schema_exists, "schema_name": "test_schema", "tables": tables}

def _find_col(cols, name):
    return next((c for c in cols if c["name"] == name), None)

def _cols_from_obj(obj):
    return [{"name": c["name"], "data_type": c["data_type"], "is_nullable": True}
            for c in obj["columns"]]

