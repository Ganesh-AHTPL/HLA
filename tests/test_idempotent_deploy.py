# TEST 8 — Missing generated column ? complete valid ALTER OR INVALID (no partial SQL)
# ------------------------------------------------------------------------------
def test_8_missing_generated_column():
    # identity column — PG supports ALTER ADD COLUMN ... GENERATED BY DEFAULT AS IDENTITY
    ddl = """
    CREATE TABLE schema1.with_identity2 (
        id   BIGINT GENERATED BY DEFAULT AS IDENTITY,
        name TEXT
    );
    """
    req = _parse_required_objects_from_ddl(ddl)
    id_col = _find_col(req[0]["columns"], "id")
    results = _build_alter_statements("schema1", "with_identity2", [id_col], "postgresql")
    assert len(results) == 1
    stmt, is_safe, reason = results[0]
    if is_safe:
        # Must contain the complete GENERATED clause
        assert "GENERATED" in stmt.upper() and "IDENTITY" in stmt.upper(), \
            f"Incomplete identity ALTER: {stmt}"
        # Must NOT be a partial/truncated fragment
        assert not re.search(r'GENERATED\s*;', stmt, re.IGNORECASE), f"Truncated ALTER: {stmt}"
        assert not re.search(r'GENERATED\s+BY\s*;', stmt, re.IGNORECASE), f"Truncated ALTER: {stmt}"
    else:
        # If classified as unsafe, the reason must explain why (not just fail silently)
        assert reason and len(reason) > 5, f"Unsafe reason too vague: {reason}"

    # generated STORED column — must never produce valid ALTER (unsafe)
    ddl2 = """
    CREATE TABLE schema1.with_stored (
        price NUMERIC(10,2),
        total NUMERIC GENERATED ALWAYS AS (price * 1.1) STORED
    );
    """
    req2 = _parse_required_objects_from_ddl(ddl2)
    total_col = _find_col(req2[0]["columns"], "total")
    results2 = _build_alter_statements("schema1", "with_stored", [total_col], "postgresql")
    stmt2, is_safe2, reason2 = results2[0]
    assert not is_safe2, f"Stored-generated ALTER must be unsafe: {stmt2}"
    # The stmt must start with -- (comment) not with ALTER
    assert stmt2.startswith("--"), f"Unsafe stmt should be a comment: {stmt2}"
    print("TEST 8 PASS — generated column: complete valid ALTER or properly INVALID (no partial SQL)")

