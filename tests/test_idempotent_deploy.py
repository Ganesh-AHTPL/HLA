# TEST 10 — Repeated deployment remains idempotent
# ------------------------------------------------------------------------------
def test_10_idempotent():
    ddl = """
    CREATE TABLE schema1.stable (
        id   BIGINT,
        val  NUMERIC(10,2),
        label TEXT
    );
    """
    req = _parse_required_objects_from_ddl(ddl)
    cols = [{"name": c["name"], "data_type": c["data_type"], "is_nullable": True} for c in req[0]["columns"]]
    tables = {"stable": _existing(cols)}
    r1 = reconcile_objects(_meta(True, tables), req)
    r2 = reconcile_objects(_meta(True, tables), req)
    assert r1["counts"] == r2["counts"]
    assert r1["counts"]["existing"] == 1
    assert r1["counts"]["missing"] == 0
    print("TEST 10 PASS — repeated reconciliation is idempotent")

