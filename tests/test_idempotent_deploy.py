# TEST 6 — Constraints are NOT parsed as columns
# ------------------------------------------------------------------------------
def test_6_constraints_not_columns():
    ddl = """
    CREATE TABLE schema1.constrained (
        id     BIGINT NOT NULL,
        ref_id INTEGER NOT NULL,
        name   TEXT,
        PRIMARY KEY (id),
        UNIQUE (name),
        FOREIGN KEY (ref_id) REFERENCES other(id),
        CHECK (id > 0),
        CONSTRAINT uq_name UNIQUE (name)
    );
    """
    req = _parse_required_objects_from_ddl(ddl)
    cols = req[0]["columns"]
    names = [c["name"] for c in cols]
    # Only id, ref_id, name should appear
    assert "id" in names
    assert "ref_id" in names
    assert "name" in names
    # Constraints must NOT appear as columns
    for bad in ("primary", "unique", "foreign", "check", "constraint"):
        assert not any(bad in n.lower() for n in names), \
            f"Constraint keyword found as column name: {names}"
    assert len(cols) == 3, f"Expected 3 columns, got {len(cols)}: {names}"
    print("TEST 6 PASS — constraints excluded from column list")

