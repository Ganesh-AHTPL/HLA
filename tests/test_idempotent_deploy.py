# TEST 4 — DEFAULT expression: TIMESTAMP DEFAULT CURRENT_TIMESTAMP
# ------------------------------------------------------------------------------
def test_4_default_expression():
    ddl = """
    CREATE TABLE schema1.with_default (
        id         SERIAL PRIMARY KEY,
        created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
        label      VARCHAR(64) DEFAULT 'unknown'
    );
    """
    req = _parse_required_objects_from_ddl(ddl)
    cols = req[0]["columns"]
    names = {c["name"] for c in cols}
    # id comes from SERIAL — still a column
    assert "created_at" in names and "label" in names, f"Missing cols in: {names}"
    ca = _find_col(cols, "created_at")
    assert "timestamp" in ca["data_type"].lower(), f"created_at type: {ca['data_type']}"
    # full_definition must preserve DEFAULT clause
    assert "DEFAULT" in ca["full_definition"].upper(), \
        f"created_at full_def: {ca['full_definition']}"
    # ALTER statement must include the full_definition (including DEFAULT)
    results = _build_alter_statements("s", "t", [ca], "postgresql")
    stmt, is_safe, reason = results[0]
    assert is_safe, f"DEFAULT column ALTER should be safe: {reason}"
    assert "DEFAULT CURRENT_TIMESTAMP" in stmt.upper() or "DEFAULT" in stmt, \
        f"ALTER missing DEFAULT: {stmt}"
    print("TEST 4 PASS — DEFAULT expression preserved")

